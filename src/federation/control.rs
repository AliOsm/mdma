pub struct Signer {
    key_id: String,
    key: KeyPairHandle,
}

impl Signer {
    pub fn new(
        store: &Store,
        key_id: String,
        key: KeyPairHandle,
    ) -> Result<Self, super::trust::Error> {
        let approved = store.local_signer(
            &key_id,
            utc_ms().map_err(|_| super::trust::Error::Denied("invalid UTC clock"))?,
        )?;
        if approved.bytes()? != key.public_key_bytes() {
            return Err(super::trust::Error::Denied(
                "selected private key does not match local signer approval",
            ));
        }
        Ok(Self { key_id, key })
    }

    pub fn key_id(&self) -> &str {
        &self.key_id
    }
    pub fn public_key(&self) -> [u8; 32] {
        self.key.public_key_bytes()
    }
}

#[derive(Clone)]
pub struct ControlService {
    store: Arc<Store>,
    signer: Arc<Signer>,
    rate: Arc<Mutex<BTreeMap<String, (Instant, u32)>>>,
    inventory: Arc<dyn Inventory>,
    shutdown: Option<WeakShutdownGuard>,
    execution: Option<super::execution::Service>,
    install: Option<super::install::Service>,
}

/// The connection's authenticated peer. Rama stores transport metadata in
/// Ingress, distinct from caller-supplied gRPC extensions and HTTP headers.
fn ingress_binding<T>(request: &Request<T>) -> Result<Binding, Status> {
    let ingress = request
        .extensions()
        .get_ref::<Ingress<Extensions>>()
        .ok_or_else(|| Status::unauthenticated("authenticated TLS ingress absent"))?;
    Ok(ingress
        .0
        .get_ref::<Binding>()
        .ok_or_else(|| Status::unauthenticated("federation TLS binding absent"))?
        .clone())
}

fn clock() -> Result<(u64, Instant), Status> {
    Ok((
        utc_ms().map_err(|_| Status::unavailable("invalid UTC clock"))?,
        Instant::now(),
    ))
}

impl ControlService {
    pub fn new(store: Arc<Store>, signer: Signer) -> Self {
        Self {
            store,
            signer: Arc::new(signer),
            rate: Arc::new(Mutex::new(BTreeMap::new())),
            inventory: Arc::new(inventory::Empty),
            shutdown: None,
            execution: None,
            install: None,
        }
    }

    pub(crate) fn with_inventory(mut self, inventory: Arc<dyn Inventory>) -> Self {
        self.inventory = inventory;
        self
    }

    pub(crate) fn with_shutdown(mut self, shutdown: Option<WeakShutdownGuard>) -> Self {
        self.shutdown = shutdown;
        self
    }

    pub(crate) fn with_execution(mut self, executor: Arc<dyn super::execution::Executor>) -> Self {
        self.execution = Some(super::execution::Service::new(self.store.clone(), executor));
        self
    }

    /// Accept models from peers holding the install grant.
    pub(crate) fn with_install(mut self, folder: Arc<dyn super::install::Folder>) -> Self {
        self.install = Some(super::install::Service::new(self.store.clone(), folder));
        self
    }

    fn inventory(&self, exports: &[String]) -> inventory::Snapshot {
        let mut snapshot = self.inventory.snapshot(exports);
        if inventory::draining(self.shutdown.as_ref()) {
            snapshot.state = ServerState::Draining;
            for model in &mut snapshot.models {
                model.ready = false;
            }
        }
        snapshot
    }

    /// Bounded control messages and responses; use on the dedicated listener.
    pub fn into_server(self) -> FederationServer<Self> {
        FederationServer::new(self)
            .with_max_decoding_message_size(96 * 1024)
            .with_max_encoding_message_size(catalog::MAX_DECIDE_RESULT_BYTES as usize + 2048)
    }

    fn binding<T>(
        &self,
        request: &Request<T>,
        origin: &str,
        destination: &str,
        action: Action<'_>,
        now_ms: u64,
        now: Instant,
    ) -> Result<(Binding, u64), Status> {
        self.admit(
            ingress_binding(request)?,
            origin,
            destination,
            action,
            now_ms,
            now,
        )
    }

    /// The peer's authorization and control budget for one RPC.
    fn admit(
        &self,
        binding: Binding,
        origin: &str,
        destination: &str,
        action: Action<'_>,
        now_ms: u64,
        now: Instant,
    ) -> Result<(Binding, u64), Status> {
        if binding.role() != TlsRole::ClientAuth || origin != binding.server_id() {
            return Err(Status::unauthenticated(
                "origin does not match inbound mTLS principal",
            ));
        }
        let snapshot = binding
            .authorize(&self.store, action, now_ms, now)
            .map_err(|_| {
                Status::permission_denied("current peer identity/state/grants deny RPC")
            })?;
        if destination != snapshot.server_id {
            return Err(Status::invalid_argument("wrong destination"));
        }
        let record = snapshot
            .peer(origin)
            .ok_or_else(|| Status::permission_denied("unknown peer"))?;
        let mut rate = self
            .rate
            .lock()
            .map_err(|_| Status::internal("control budget lock poisoned"))?;
        rate.retain(|_, (start, _)| {
            now.saturating_duration_since(*start) < Duration::from_secs(60)
        });
        if rate.len() >= super::config::MAX_PEERS && !rate.contains_key(origin) {
            return Err(Status::resource_exhausted("control budget full"));
        }
        let (_, count) = rate.entry(origin.into()).or_insert((now, 0));
        if *count >= record.policy.limits.control_per_minute {
            return Err(Status::resource_exhausted("peer control rate exceeded"));
        }
        *count += 1;
        Ok((binding, snapshot.generation))
    }

    /// The model's descriptor, once the peer may execute it. A model the
    /// peer may not execute is denied whether or not it exists.
    fn executable(
        &self,
        execution: &super::execution::Service,
        binding: &Binding,
        generation: u64,
        model: &str,
    ) -> Result<catalog::ModelDescriptor, Status> {
        let descriptor = execution.executor().descriptor(model);
        let operation = descriptor.as_ref().map_or(
            super::config::Operation::Synthesize,
            catalog::ModelDescriptor::operation,
        );
        self.final_check(binding, Action::Execute { model, operation }, generation)?;
        descriptor
    }

    fn install(&self) -> Result<&super::install::Service, Status> {
        self.install
            .as_ref()
            .ok_or_else(|| Status::unimplemented("install_disabled"))
    }

    fn execution(&self) -> Result<&super::execution::Service, Status> {
        self.execution
            .as_ref()
            .ok_or_else(|| Status::unimplemented("execution_disabled"))
    }

    fn final_check(
        &self,
        binding: &Binding,
        action: Action<'_>,
        generation: u64,
    ) -> Result<(), Status> {
        let (wall, mono) = clock()?;
        let snapshot = binding
            .authorize(&self.store, action, wall, mono)
            .map_err(|_| Status::permission_denied("peer authorization changed"))?;
        if snapshot.generation != generation {
            return Err(Status::aborted("trust changed while preparing response"));
        }
        Ok(())
    }
}

impl Federation for ControlService {
    type SynthesizeStream = super::execution::EventStream;

    async fn acquire_lease(
        &self,
        request: Request<LeaseRequest>,
    ) -> Result<Response<LeaseGrant>, Status> {
        let execution = self.execution()?;
        let message = request.get_ref();
        let (wall, mono) = clock()?;
        let (binding, generation) = self.binding(
            &request,
            &message.origin,
            &message.destination,
            Action::Authenticate,
            wall,
            mono,
        )?;
        let descriptor = self.executable(execution, &binding, generation, &message.model)?;
        if descriptor.artifact_id != message.artifact_id
            || descriptor.profile_id != message.profile_id
        {
            return Err(Status::failed_precondition("selection_changed"));
        }
        execution
            .executor()
            .lease(
                &message.origin,
                &message.model,
                crate::registry::requested_ttl(message.ttl_ms),
            )
            .map(Response::new)
    }

    async fn renew_lease(
        &self,
        request: Request<LeaseRenewal>,
    ) -> Result<Response<LeaseGrant>, Status> {
        let execution = self.execution()?;
        let message = request.get_ref();
        let (wall, mono) = clock()?;
        let (binding, generation) = self.binding(
            &request,
            &message.origin,
            &message.destination,
            Action::Authenticate,
            wall,
            mono,
        )?;
        let model = execution
            .executor()
            .lease_model(&message.origin, &message.lease_id)?;
        // A peer that lost the grant cannot renew; its lease runs out.
        self.executable(execution, &binding, generation, &model)?;
        execution
            .executor()
            .renew_lease(
                &message.origin,
                &message.lease_id,
                crate::registry::requested_ttl(message.ttl_ms),
            )
            .map(Response::new)
    }

    async fn release_lease(
        &self,
        request: Request<LeaseRelease>,
    ) -> Result<Response<LeaseReleased>, Status> {
        let execution = self.execution()?;
        let message = request.get_ref();
        let (wall, mono) = clock()?;
        // Giving a lease up needs no grant, only the peer's own connection.
        self.binding(
            &request,
            &message.origin,
            &message.destination,
            Action::Authenticate,
            wall,
            mono,
        )?;
        execution
            .executor()
            .release_lease(&message.origin, &message.lease_id)?;
        Ok(Response::new(LeaseReleased {}))
    }

    async fn decide(
        &self,
        request: Request<DecideRequest>,
    ) -> Result<Response<DecideResponse>, Status> {
        let execution = self.execution()?;
        execution.decide(request).await.map(|done| {
            let response = Response::new(done.response);
            response.extensions().insert(done.lease);
            response
        })
    }

    async fn synthesize(
        &self,
        request: Request<SynthesizeRequest>,
    ) -> Result<Response<Self::SynthesizeStream>, Status> {
        let execution = self.execution()?;
        if let Some(envelope) = &request.get_ref().envelope {
            execution
                .load(&request, envelope, super::config::Operation::Synthesize)?
                .await?;
        }
        execution.synthesize(request).map(Response::new)
    }

    async fn install(
        &self,
        request: Request<InstallRequest>,
    ) -> Result<Response<InstallPlan>, Status> {
        let install = self.install()?;
        let (wall, mono) = clock()?;
        let message = request.get_ref();
        let (binding, _) = self.binding(
            &request,
            &message.origin,
            &message.destination,
            Action::Install,
            wall,
            mono,
        )?;
        install
            .install(binding.server_id().to_owned(), request.into_inner())
            .await
            .map(Response::new)
    }

    async fn upload(
        &self,
        request: Request<Streaming<UploadPart>>,
    ) -> Result<Response<InstallPlan>, Status> {
        let install = self.install()?;
        let binding = ingress_binding(&request)?;
        let mut parts = request.into_inner();
        let first = tokio::time::timeout(Duration::from_secs(30), parts.message())
            .await
            .map_err(|_| Status::deadline_exceeded("upload stalled"))??;
        let Some(UploadPart {
            part: Some(upload_part::Part::Request(message)),
        }) = first
        else {
            return Err(Status::invalid_argument(
                "an upload starts with its request",
            ));
        };
        let (wall, mono) = clock()?;
        let (binding, _) = self.admit(
            binding,
            &message.origin,
            &message.destination,
            Action::Install,
            wall,
            mono,
        )?;
        install
            .upload(binding, message, parts)
            .await
            .map(Response::new)
    }

    async fn identify(
        &self,
        request: Request<IdentifyRequest>,
    ) -> Result<Response<IdentifyResponse>, Status> {
        let message = request.get_ref();
        if message.supported_major_versions.len() > 16 {
            return Err(Status::invalid_argument(
                "too many supported protocol versions",
            ));
        }
        let (wall, mono) = clock()?;
        let (binding, generation) = self.binding(
            &request,
            &message.origin,
            &message.destination,
            Action::Identify,
            wall,
            mono,
        )?;
        if !message.supported_major_versions.contains(&1) {
            return Err(Status::failed_precondition(
                "no common federation major version",
            ));
        }
        let response = IdentifyResponse {
            server_id: message.destination.clone(),
            supported_major_versions: vec![1],
        };
        self.final_check(&binding, Action::Identify, generation)?;
        Ok(Response::new(response))
    }

    async fn scan_capabilities(
        &self,
        request: Request<ScanCapabilitiesRequest>,
    ) -> Result<Response<SignedCatalog>, Status> {
        let message = request.get_ref();
        if message.major_version != 1 || message.nonce.len() != catalog::NONCE_BYTES {
            return Err(Status::invalid_argument(
                "major version 1 and a 32-byte nonce required",
            ));
        }
        let (wall, mono) = clock()?;
        let (binding, generation) = self.binding(
            &request,
            &message.origin,
            &message.destination,
            Action::ScanCapabilities,
            wall,
            mono,
        )?;
        let snapshot = self
            .store
            .snapshot()
            .map_err(|_| Status::unavailable("trust state unavailable"))?;
        let peer = snapshot
            .peer(&message.origin)
            .ok_or_else(|| Status::permission_denied("unknown peer"))?;
        if snapshot.generation != generation {
            return Err(Status::aborted("trust changed before inventory"));
        }
        let exports = snapshot.catalog_exports(peer);
        let inventory = self.inventory(&exports);
        let key = self
            .store
            .local_signer(&self.signer.key_id, wall)
            .map_err(|_| Status::unavailable("selected local signer not currently eligible"))?;
        if key
            .bytes()
            .map_err(|_| Status::internal("invalid local key approval"))?
            != self.signer.public_key()
        {
            return Err(Status::unavailable("selected local key material changed"));
        }
        let body = CatalogBody {
            origin: message.destination.clone(),
            destination: message.origin.clone(),
            nonce: message.nonce.clone(),
            issued_at_ms: wall,
            expires_at_ms: wall
                .saturating_add(catalog::MAX_CATALOG_LIFETIME_MS)
                .min(key.window.valid_until_ms),
            server_state: inventory.state,
            models: inventory.models.clone(),
            host: inventory.host.clone(),
        };
        let signed =
            catalog::sign_catalog(&body, &self.signer.key_id, &self.signer.key).map_err(|_| {
                Status::unavailable("cannot issue catalog within selected signer window")
            })?;
        self.store
            .local_signer(&self.signer.key_id, clock()?.0)
            .map_err(|_| Status::unavailable("local signer authorization changed"))?;
        if !self.inventory(&exports).same_offer(&inventory) {
            return Err(Status::aborted(
                "native inventory/readiness changed while signing",
            ));
        }
        self.final_check(&binding, Action::ScanCapabilities, generation)?;
        if clock()?.0 >= body.expires_at_ms {
            return Err(Status::unavailable("catalog expired while signing"));
        }
        Ok(Response::new(SignedCatalog {
            key_id: signed.key_id,
            body_json: signed.body_json,
            signature: signed.signature.to_vec(),
        }))
    }
}

