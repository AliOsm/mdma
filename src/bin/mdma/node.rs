#[derive(Debug, usage_rs::Args)]
pub(super) struct Args {
    #[usage(subcommand)]
    command: Command,
}

#[derive(Debug, usage_rs::Subcommands)]
enum Command {
    /// Run the insecure resource-only daemon (one MDMA daemon per machine).
    Serve(ServeArgs),
    /// Query explicitly supplied HTTP peers once; unreachable peers are reported.
    Scan(ScanArgs),
    /// Discover LAN nodes through mDNS and fetch resource snapshots.
    Discover(discovery::Args),
    /// Inspect the local NIC owning an IP; read-only, no daemon required.
    Interface(InterfaceArgs),
}

#[derive(Debug, usage_rs::Args)]
struct InterfaceArgs {
    /// Local interface IP; replace the example 192.0.2.10 with your LAN IP.
    #[usage(long)]
    address: String,
}

#[derive(Debug, usage_rs::Args)]
struct ServeArgs {
    /// Explicit LAN listen address; replace the example 192.0.2.10:50052.
    #[usage(long)]
    listen: String,
    /// Existing model-storage directory; reports its containing filesystem.
    #[usage(long)]
    storage: PathBuf,
    /// Disable mDNS advertisement/browsing; retain explicit-address RPC only.
    #[usage(long)]
    no_discovery: bool,
    /// Minimum acceptable peer release version; defaults to this binary's version.
    #[usage(long)]
    min_peer_version: Option<String>,
    /// Optional exact build ID allow-list pin (Git commit or release build token).
    #[usage(long)]
    require_peer_build: Option<String>,
}

#[derive(Debug, usage_rs::Args)]
struct ScanArgs {
    /// Comma-separated HTTP origins; replace the example http://192.0.2.10:50052.
    #[usage(long)]
    peers: String,
    #[usage(long)]
    min_peer_version: Option<String>,
    #[usage(long)]
    require_peer_build: Option<String>,
}

struct NodeService {
    storage: PathBuf,
    address: std::net::IpAddr,
    policy: version::Policy,
}

fn snapshot(
    storage: &std::path::Path,
    address: Option<std::net::IpAddr>,
) -> Result<proto::ResourceSnapshot, BoxError> {
    let mut system = System::new();
    system.refresh_memory();
    system.refresh_cpu_all();
    let (disk_total_bytes, disk_available_bytes) =
        mdma::host::disk_of(storage).ok_or("cannot determine filesystem for model storage")?;
    Ok(proto::ResourceSnapshot {
        node_name: System::host_name().ok_or("cannot determine hostname")?,
        os: std::env::consts::OS.into(),
        architecture: std::env::consts::ARCH.into(),
        mdma_version: env!("CARGO_PKG_VERSION").into(),
        collected_at_unix_ms: SystemTime::now()
            .duration_since(UNIX_EPOCH)?
            .as_millis()
            .try_into()?,
        cpu_model: system
            .cpus()
            .first()
            .map(|cpu| cpu.brand().to_owned())
            .unwrap_or_default(),
        logical_cpu_count: system.cpus().len().try_into()?,
        memory_total_bytes: system.total_memory(),
        memory_available_bytes: system.available_memory(),
        storage_path: storage.to_string_lossy().into_owned(),
        disk_total_bytes,
        disk_available_bytes,
        network_interface: address.and_then(network::interface),
        identity: Some(version::local()),
    })
}

impl proto::node_server::Node for NodeService {
    async fn identify(
        &self,
        request: Request<proto::IdentifyRequest>,
    ) -> Result<Response<proto::NodeIdentity>, Status> {
        self.policy
            .check(request.into_inner().requester.as_ref())
            .map_err(Status::failed_precondition)?;
        Ok(Response::new(version::local()))
    }

    async fn scan_capabilities(
        &self,
        request: Request<proto::ScanCapabilitiesRequest>,
    ) -> Result<Response<proto::ResourceSnapshot>, Status> {
        self.policy
            .check(request.into_inner().requester.as_ref())
            .map_err(Status::failed_precondition)?;
        let storage = self.storage.clone();
        let address = self.address;
        let snapshot = tokio::task::spawn_blocking(move || snapshot(&storage, Some(address)))
            .await
            .map_err(|error| Status::internal(error.to_string()))?
            .map_err(|error| Status::unavailable(error.to_string()))?;
        Ok(Response::new(snapshot))
    }
}

struct Transport(BoxService<rama::http::Request, rama::http::Response, OpaqueError>);

impl Service<rama::http::Request> for Transport {
    type Output = rama::http::Response;
    type Error = Status;

    async fn serve(&self, request: rama::http::Request) -> Result<Self::Output, Status> {
        self.0
            .serve(request)
            .await
            .map_err(|error| Status::unavailable(error.to_string()))
    }
}

fn peer_origin(peer: &str) -> Result<Uri, BoxError> {
    let uri: Uri = peer.parse()?;
    if uri.scheme_str() != Some("http")
        || uri.host().is_none()
        || uri.userinfo().is_some()
        || uri.path_or_root() != "/"
        || uri.query().is_some()
        || uri.fragment().is_some()
    {
        return Err("POC peers must be http://host:port origins".into());
    }
    Ok(uri)
}

async fn scan(args: ScanArgs) -> Result<(), BoxError> {
    let policy = version::Policy::new(
        args.min_peer_version.as_deref(),
        args.require_peer_build.as_deref(),
    )?;
    let peers = args
        .peers
        .split(',')
        .map(str::trim)
        .map(|peer| Ok((peer, peer_origin(peer)?)))
        .collect::<Result<Vec<_>, BoxError>>()?;
    let mut failed = false;
    for (peer, _) in peers {
        match query(peer, &policy).await {
            Ok(resources) => {
                let mut resources = resources;
                resources["peer"] = peer.into();
                resources["status"] = "reachable".into();
                println!("{resources}");
            }
            Err(error) => {
                failed = true;
                println!(
                    "{}",
                    serde_json::json!({"peer": peer, "status": error.status(), "error": error.to_string(),
                    "identity": match &error {
                        version::QueryError::Rejected { identity, .. } => identity.clone(),
                        version::QueryError::Unreachable(_) => None,
                    }})
                );
            }
        }
    }
    if failed {
        Err("one or more peers rejected or unreachable".into())
    } else {
        Ok(())
    }
}

async fn query(
    peer: &str,
    policy: &version::Policy,
) -> Result<serde_json::Value, version::QueryError> {
    // No extra latency probes or usable snapshots before compatibility succeeds.
    let mut resources = query_resources(peer, policy).await?;
    let origin = peer_origin(peer).map_err(|error| error.to_string())?;
    // Discovery endpoints are numeric. Do not add blocking DNS to latency probes.
    let endpoint = origin
        .host()
        .and_then(|host| host.to_string().trim_matches(['[', ']']).parse().ok())
        .map(|ip| std::net::SocketAddr::new(ip, origin.port_u16().unwrap_or(80)));
    let probe = async {
        match endpoint {
            Some(endpoint) => tokio::task::spawn_blocking(move || network::probe(endpoint))
                .await
                .map_err(|error| error.to_string())?,
            None => Err("TCP latency probe requires a numeric IP endpoint".into()),
        }
    };
    let observation = probe.await;
    resources["network_observation"] = match observation {
        Ok(observation) => observation,
        Err(error) => serde_json::json!({"error": error}),
    };
    Ok(resources)
}

async fn query_resources(
    peer: &str,
    policy: &version::Policy,
) -> Result<serde_json::Value, version::QueryError> {
    let origin = peer_origin(peer).map_err(|error| error.to_string())?;
    let connector = EasyHttpConnectorBuilder::new()
        .with_default_transport_connector()
        .with_default_dns_connector()
        .without_tls_proxy_support()
        .without_proxy_support()
        .without_tls_support()
        .with_default_http_connector::<Body>(Executor::default())
        .without_connection_pool()
        .build_client::<Body, Body, _>();
    let client = proto::node_client::NodeClient::new(Transport(BoxService::new(connector)), origin);
    tokio::time::timeout(Duration::from_secs(5), async {
            let identity = client.identify(proto::IdentifyRequest { requester: Some(version::local()) })
                .await.map_err(version::QueryError::from_status)?.into_inner();
            policy.check(Some(&identity)).map_err(|reason| version::QueryError::Rejected {
                reason, identity: Some(version::json_identity(&identity)),
            })?;
            let start = std::time::Instant::now();
            let response = client.scan_capabilities(proto::ScanCapabilitiesRequest {
                requester: Some(version::local()),
            }).await.map_err(version::QueryError::from_status)?;
            let rpc_elapsed_ms = start.elapsed().as_secs_f64() * 1000.0;
            let s = response.into_inner();
            if s.identity.as_ref() != Some(&identity) || s.mdma_version != identity.mdma_version {
                return Err(version::QueryError::Rejected {
                    reason: "resource/handshake identity mismatch".into(),
                    identity: s.identity.as_ref().map(version::json_identity),
                });
            }
            Ok(serde_json::json!({
                "identity": version::json_identity(&identity),
                "node_name": s.node_name,
                "os": s.os, "architecture": s.architecture, "mdma_version": s.mdma_version,
                "collected_at_unix_ms": s.collected_at_unix_ms,
                "cpu_model": s.cpu_model, "logical_cpu_count": s.logical_cpu_count,
                "memory_total_bytes": s.memory_total_bytes, "memory_available_bytes": s.memory_available_bytes,
                "storage_path": s.storage_path, "disk_total_bytes": s.disk_total_bytes,
                "disk_available_bytes": s.disk_available_bytes,
                "network_interface": network::json(s.network_interface),
                "resource_rpc_elapsed_ms": rpc_elapsed_ms,
            }))
    }).await.unwrap_or_else(|_| Err(version::QueryError::Unreachable("identity/resource timeout after 5 seconds".into())))
}

pub(super) fn run(args: Args) -> Result<(), Box<dyn std::error::Error>> {
    let result = tokio::runtime::Builder::new_multi_thread()
        .enable_all()
        .build()?
        .block_on(async {
            match args.command {
                Command::Scan(args) => scan(args).await,
                Command::Discover(args) => discovery::discover(args).await,
                Command::Interface(args) => {
                    let address = args.address.parse()?;
                    let nic = tokio::task::spawn_blocking(move || network::interface(address))
                        .await?
                        .ok_or("no local interface owns that IP")?;
                    println!("{}", network::json(Some(nic)));
                    Ok(())
                }
                Command::Serve(args) => {
                    let policy = version::Policy::new(args.min_peer_version.as_deref(), args.require_peer_build.as_deref())?;
                    let _lock = mdma::singleton::MachineLock::acquire()?;
                    let storage = args.storage.canonicalize()?;
                    if !storage.is_dir() {
                        return Err("storage must be an existing directory".into());
                    }
                    // Fail before listening if resource collection is unsupported.
                    let _ = snapshot(&storage, None)?;
                    let listen: std::net::SocketAddr = args.listen.parse()?;
                    if !args.no_discovery && !discovery::usable_ip(listen.ip()) {
                        return Err("mDNS requires an explicit LAN IP (not wildcard, loopback or IPv6 link-local); use --no-discovery for explicit-address-only mode".into());
                    }
                    let stop = discovery::shutdown_signal()?;
                    let executor = Executor::default();
                    let listener = TcpListener::bind_address(args.listen, executor.clone()).await?;
                    let address = listener.local_addr()?.to_string().parse()?;
                    let mut discovery = if args.no_discovery { None } else {
                        Some(discovery::Discovery::start(Some(address), policy.clone())?)
                    };
                    eprintln!(
                        "INSECURE resource POC listening on {}; private LAN only",
                        listener.local_addr()?
                    );
                    let service = HttpServer::auto(executor)
                        .service(proto::node_server::NodeServer::new(NodeService { storage, address: listen.ip(), policy }));
                    let result = tokio::select! {
                        () = listener.serve(service) => Ok(()),
                        result = async {
                            match discovery.as_ref() {
                                Some(discovery) => discovery.watch(None).await,
                                None => std::future::pending::<Result<(), BoxError>>().await,
                            }
                        } => result,
                        () = stop => Ok(()),
                    };
                    if let Some(discovery) = discovery.as_mut() { discovery.close().await; }
                    result
                }
            }
        });
    result.map_err(|error| error.to_string().into())
}

